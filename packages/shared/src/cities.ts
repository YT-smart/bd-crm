/** 城市 -> 所属省份（城市名在全国范围内唯一） */
export const PROVINCE_OF_CITY: Record<string, Province> = Object.fromEntries(
  (Object.entries(CITIES_BY_PROVINCE) as [Province, readonly string[]][]).flatMap(([p, cs]) => cs.map((c) => [c, p])),
);

/** 全部可选城市 */
export const ALL_CITIES: readonly string[] = Object.keys(PROVINCE_OF_CITY);

export function isCity(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(PROVINCE_OF_CITY, name);
}

/** 去掉用户输入中的「市」后缀，便于搜索匹配：杭州市 -> 杭州 */
export function normalizeCityKeyword(kw: string): string {
  return kw.trim().replace(/市$/, '');
}
